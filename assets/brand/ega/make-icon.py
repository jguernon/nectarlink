"""The NectarLink EGA icon, from one list of rectangles.

Same template as the author's other EGA apps (Claude Vision, Compudash,
NewsFlip, NewXFlip): black tile, blue title band, double gray frame, the 16
EGA colors. Inside: the phone and the PC, linked by a drop of nectar.

Writes, from the same drawing:
  assets/brand/ega/icon-ega.svg                         the scalable icon
  desktop/app/src/mark_ega.rs                           the rectangles for mark.rs
  android/app/src/main/res/drawable/ic_launcher_*.xml   the adaptive icon layers

Run from anywhere: python3 assets/brand/ega/make-icon.py
"""
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))

BLACK, BLUE, GREEN, CYAN = "#000000", "#0000AA", "#00AA00", "#00AAAA"
GRAY, DGRAY, BROWN = "#AAAAAA", "#555555", "#AA5500"
LGREEN, LCYAN, LRED, LMAGENTA = "#55FF55", "#55FFFF", "#FF5555", "#FF55FF"
YELLOW, WHITE = "#FFFF55", "#FFFFFF"

# The tile: a rounded square from 1 to 63 (radius 11) in DGRAY, black inside
# from 3 to 61 (radius 9), as `rx=10, stroke-width=2` in the other icons.
TILE_OUT = (1.0, 11.0)
TILE_IN = (3.0, 9.0)

R = []          # (x, y, w, h, color), painted in order


def rect(x, y, w, h, c):
    R.append((x, y, w, h, c))


def frame(x, y, w, h, sw, c):
    """A stroked rectangle (centered on its edge, like SVG) as four fills."""
    h2 = sw / 2
    rect(x - h2, y - h2, w + sw, sw, c)
    rect(x - h2, y + h - h2, w + sw, sw, c)
    rect(x - h2, y + h2, sw, h - sw, c)
    rect(x + w - h2, y + h2, sw, h - sw, c)


# Title band: cursor, title, the phone's battery on the right.
rect(7, 8, 50, 8, BLUE)
rect(9, 9.5, 2, 5, WHITE)
rect(12, 10.5, 15, 3, YELLOW)
rect(44.5, 10.5, 8.5, 3, LGREEN)
rect(53, 11.25, 1.5, 1.5, LGREEN)

# The double frame of the page.
frame(7.5, 19.5, 49, 37, 1.2, GRAY)
frame(9.6, 21.6, 44.8, 32.8, 1.2, GRAY)

# The phone: cyan body, blue screen with its notifications, home bar.
frame(13, 24, 12, 24, 1.2, LCYAN)
rect(14.6, 25.6, 8.8, 17.6, BLUE)
rect(15.8, 27, 4, 1.5, YELLOW)
rect(15.8, 30, 6.4, 1.5, WHITE)
rect(15.8, 32.5, 5, 1.5, WHITE)
rect(15.8, 35.5, 6.4, 1.5, LMAGENTA)
rect(15.8, 38, 4.5, 1.5, GRAY)
rect(17.5, 45, 3, 1.2, LCYAN)

# The PC: cyan monitor, blue screen, gray stand.
frame(34, 24.5, 18, 14, 1.2, LCYAN)
rect(35.2, 25.7, 15.6, 11.6, BLUE)
rect(36.5, 27, 9, 1.5, WHITE)
rect(36.5, 29.5, 12, 1.5, GRAY)
rect(36.5, 32, 10, 1.5, GRAY)
rect(36.5, 34.5, 5, 1.5, LGREEN)
rect(41.5, 38.5, 3, 3, GRAY)
rect(37.5, 41.5, 11, 1.5, GRAY)

# The link: a drop of nectar over a dotted line, phone to PC.
rect(29, 26.5, 1.5, 1.5, YELLOW)
rect(28.25, 28, 3, 1.5, YELLOW)
rect(27.5, 29.5, 4.5, 2.5, YELLOW)
rect(28.25, 32, 3, 1, YELLOW)
rect(28.25, 29.5, 1, 1, WHITE)
for x in (26.25, 28.75, 31.25):
    rect(x, 35.5, 1.5, 1.5, YELLOW)

# Status strip: connected (green), the phone's name, the link.
rect(12.5, 50.5, 7.5, 2.5, GREEN)
rect(17.5, 51, 1.5, 1.5, WHITE)
rect(21.5, 51, 11, 1.5, WHITE)
rect(34, 51, 1.5, 1.5, YELLOW)
rect(37, 51, 14.5, 1.5, LCYAN)


def num(v):
    return ("%.2f" % v).rstrip("0").rstrip(".")


def write(rel, text):
    path = os.path.join(ROOT, rel)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", rel)


# ---- SVG ----
svg = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64">',
       '  <!-- NectarLink, EGA: generated by make-icon.py, edit the script instead -->',
       '  <rect x="2" y="2" width="60" height="60" rx="10" fill="#000000" stroke="#555555" stroke-width="2"/>']
for x, y, w, h, c in R:
    svg.append(f'  <rect x="{num(x)}" y="{num(y)}" width="{num(w)}" height="{num(h)}" fill="{c}"/>')
svg.append("</svg>\n")
write("assets/brand/ega/icon-ega.svg", "\n".join(svg))

# ---- Rust ----
rs = ["// SPDX-License-Identifier: GPL-3.0-or-later",
      "// Generated by assets/brand/ega/make-icon.py: edit the script instead.",
      "// Included by mark.rs. The EGA icon in a 64×64 grid.",
      "",
      f"/// The tile: outer rounded square (inset, radius) in dark gray, then the black inside.",
      f"const EGA_TILE_OUT: (f32, f32) = ({TILE_OUT[0]:.1}, {TILE_OUT[1]:.1});",
      f"const EGA_TILE_IN: (f32, f32) = ({TILE_IN[0]:.1}, {TILE_IN[1]:.1});",
      "",
      "/// Rectangles painted in order: x, y, width, height, 0xRRGGBB.",
      f"const EGA_RECTS: [(f32, f32, f32, f32, u32); {len(R)}] = ["]
for x, y, w, h, c in R:
    rs.append(f"    ({x:.2f}, {y:.2f}, {w:.2f}, {h:.2f}, 0x{c[1:]}),")
rs.append("];\n")
write("desktop/app/src/mark_ega.rs", "\n".join(rs))

# ---- Android adaptive icon ----
# The 64 grid is drawn at 0.93 dp a unit, centered on the 108 dp canvas, so the
# page frame (49 units) sits inside the 66 dp safe zone's square.
SCALE = 0.93
OFF = (108 - 64 * SCALE) / 2


def path(x, y, w, h):
    return f"M{num(OFF + x * SCALE)},{num(OFF + y * SCALE)}h{num(w * SCALE)}v{num(h * SCALE)}h{num(-w * SCALE)}z"


head = ('<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- SPDX-License-Identifier: GPL-3.0-or-later -->\n'
        '<!-- {}: generated by assets/brand/ega/make-icon.py, edit the script instead. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n')
# Background: the black tile (the launcher's mask rounds it); the gray rim
# would be cut by round masks, so it is left out.
write("android/app/src/main/res/drawable/ic_launcher_background.xml",
      head.format("Adaptive icon background: the EGA black")
      + '    <path android:pathData="M0,0h108v108h-108z" android:fillColor="#000000" />\n</vector>\n')
fg = [head.format("Adaptive icon foreground: the EGA page, the phone and the PC")]
by_color = {}
for x, y, w, h, c in R:
    fg.append(f'    <path android:fillColor="{c}" android:pathData="{path(x, y, w, h)}" />\n')
fg.append("</vector>\n")
write("android/app/src/main/res/drawable/ic_launcher_foreground.xml", "".join(fg))
# Monochrome (Android 13 themed icons): the same drawing in one color, without
# the filled blue areas, which would swallow what is drawn on them.
mono = [head.format("Themed (monochrome) icon, Android 13+: the EGA page in one color")]
for x, y, w, h, c in R:
    if c == BLUE:
        continue
    mono.append(f'    <path android:fillColor="#FFFFFF" android:pathData="{path(x, y, w, h)}" />\n')
mono.append("</vector>\n")
write("android/app/src/main/res/drawable/ic_launcher_monochrome.xml", "".join(mono))
